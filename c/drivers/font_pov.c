/**
 * @file    font_pov.c
 * @brief   摇摇棒字模数据 —— 3 行 × 40 列（LOOP 4 实字模）
 *
 * == 编码约定（由 led_pov.c LED_Loop1 + 595 stage 解码决定）==
 *   font[row][col] = 1 字节位图，bit i = 该列第 i 颗 LED 状态：
 *     bit i = 1 → 该 LED 点亮 POV_ROW_COLOR[row] 的颜色（满通道：4 颗/cat 全亮）
 *     bit i = 0 → 该 LED 熄灭
 *   例：byte = 0xFF + POV_COLOR_BLUE → 该列 8 颗蓝全亮（垂直满条）
 *       byte = 0x01 + POV_COLOR_BLUE → 仅 cat 0 内 4 颗蓝亮（顶部 4 颗）
 *   == 重要 ==：POV_COLOR_* 必须满通道（B=3, G=7, R=7），否则 0xFF 列
 *              只点亮顶部 2 颗/cat = 稀疏 4 颗（用户误以为"全亮"实为融合）。
 *
 * == 字母-颜色映射（POV_ROW_COLOR[] in board_init.c）==
 *   row 0 = L（蓝色）  cols 0..15（16 列 = 16×8 像素 L 字母）
 *   row 1 = K（绿色）  cols 16..31（16 列 = 16×8 像素 K 字母）
 *   row 2 = M（红色）  cols 32..39（8 列 = 8×8 像素 M 字母，受 POV_COL_NUM=40 约束）
 *
 * == 字模手绘（16×8 / 8×8 点阵）==
 *   L：竖 + 底 = cols 0..14 全列 + col 15 仅底 LED
 *   K：竖 + 双斜 = cols 0..7 全列 + cols 8..11 上斜收 + cols 12..15 下斜展
 *   M：双竖 + 中 V = cols 0,7 全列 + cols 1..3 上厚下厚 + col 4 V 谷底
 */
#include "board.h"
#include "font_pov.h"

/* 主字模：LKM（L=蓝 K=绿 M=红）
 *   __attribute__((used)) 阻止 LTO 把它当未引用符号 GC 掉（POV 主循环 LOOP 5/6
 *   才在 Zig 侧通过 led_pov_set_pattern() 引用，当前 build 没人调 → 默认 GC）。 */
__attribute__((used))
const uint8_t FONT_LKM[POV_ROW_NUM][POV_COL_NUM] = {
    /* row 0 = L（蓝色，cols 12..27 = 16 列：2 col 竖 + 14 col 底横）
     *   前 12 列 + 后 12 列 = pad（共 24 列黑，比上一版 12 col 各少 2）
     *     cols 12..13 = 0xFF × 2   ← 竖笔 2 col 满
     *     cols 14..27 = 0x80 × 14  ← 底横笔 14 col（仅 bit 7 = 底部 1 颗 LED） */
    { 0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
      0x00,0x00,0x00,0x00,
      0xFF,0xFF,0x80,0x80,0x80,0x80,0x80,0x80,0x80,0x80,0x80,0x80,0x80,0x80,0x80,0x80,
      0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
      0x00,0x00,0x00,0x00 },

    /* row 1 = K（绿色，cols 12..27 = 16 列：7 col K 主体 + 中间断开 2 col 空像素）
     *   K 加宽到 7 col，每个斜笔画中间留 2 col 空像素把笔画"打断"成两段
     *     cols 12..15 = 0x00 × 4     ← 左 pad
     *     col  16    = 0xFF          ← 左竖满
     *     col  17    = 0x66          ← 斜臂第 1 段（靠近垂直，2-LED 厚）
     *     cols 18..19 = 0x00 × 2     ← 笔画断开：中间 2 col 黑像素（gap）
     *     col  20    = 0x66          ← 斜臂第 2 段（靠近角点，2-LED 厚）
     *     col  21    = 0xC3          ← 斜臂到达角（LEDs 0,1,6,7）
     *     col  22    = 0x81          ← 顶/底角点（LEDs 0, 7）
     *     cols 23..27 = 0x00 × 5     ← 右 pad */
    { 0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
      0x00,0x00,0x00,0x00,
      0x00,0x00,0x00,0x00,0xFF,0x66,0x00,0x00,0x66,0xC3,0x81,0x00,0x00,0x00,0x00,0x00,
      0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
      0x00,0x00,0x00,0x00 },

    /* row 2 = M（红色，cols 12..27 = 16 列：2 col 双竖 + 12 col V 谷）
     *     cols 12..13 = 0xFF × 2    ← 左竖 2 col 满
     *     col  14    = 0x02         ← V 左臂 step 1（LED 1）
     *     col  15    = 0x04         ← V 左臂 step 2（LED 2）
     *     cols 16..23 = 0x08 × 8    ← V 谷底 8 col 宽（LED 3 全亮，比 12-col 版 +4）
     *     col  24    = 0x04         ← V 右臂 step 1（LED 2）
     *     col  25    = 0x02         ← V 右臂 step 2（LED 1）
     *     cols 26..27 = 0xFF × 2    ← 右竖 2 col 满 */
    { 0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
      0x00,0x00,0x00,0x00,
      0xFF,0xFF,0x02,0x04,0x08,0x08,0x08,0x08,0x08,0x08,0x08,0x08,0x04,0x02,0xFF,0xFF,
      0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
      0x00,0x00,0x00,0x00 },
};

